// LATENT CLASH — STAGE: bake the few pixel-font glyphs the stage art uses into
// src/stages/glyphs.js (so stage art never depends on another module at runtime).
//
//   node tools/stages-glyphs.mjs
//
// The Fusion Pixel fonts are drawn on an exact pixel grid, so rendering them at their native
// size on an integer baseline and thresholding alpha gives the designed bitmap.
import { createRequire } from 'module';
import fs from 'fs';
import path from 'path';
import url from 'url';

const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const ROOT = path.dirname(path.dirname(url.fileURLToPath(import.meta.url)));

const ASCII = ' !"#%&\'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ[]_abcdefghijklmnopqrstuvwxyz{|}~';
const HANZI = '服务器正常运行评测基准场潜空间思考词元向量注意力鲸星书模型推理深度海光速训练损失分数距离你好世界猫的是我';
const SETS = { 8: ASCII + HANZI, 10: ASCII + HANZI, 12: ASCII + HANZI };

const b = await chromium.launch();
const page = await b.newPage();
const out = {};
for (const size of Object.keys(SETS)) {
  const file = path.join(ROOT, 'tools', 'fonts', `fusion-pixel-${size}px-proportional-zh_hans.otf.woff2`);
  const b64 = fs.readFileSync(file).toString('base64');
  out[size] = await page.evaluate(async ({ b64, size, chars }) => {
    const bin = Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));
    const ff = new FontFace('fp' + size, bin.buffer);
    await ff.load();
    document.fonts.add(ff);
    const S = +size, C = 4 * S;
    const cv = document.createElement('canvas'); cv.width = C; cv.height = C;
    const g = cv.getContext('2d', { willReadFrequently: true });
    const res = {}; let top = 99, bot = -1;
    const raw = {};
    for (const ch of chars) {
      g.clearRect(0, 0, C, C);
      g.font = S + 'px fp' + S; g.textBaseline = 'alphabetic'; g.fillStyle = '#fff';
      g.fillText(ch, S, 2 * S);
      const adv = Math.round(g.measureText(ch).width);
      const d = g.getImageData(0, 0, C, C).data;
      const px = [];
      for (let y = 0; y < C; y++) for (let x = 0; x < C; x++) {
        if (d[(y * C + x) * 4 + 3] >= 128) { px.push([x - S, y - 2 * S]); top = Math.min(top, y - 2 * S); bot = Math.max(bot, y - 2 * S); }
      }
      raw[ch] = { adv, px };
    }
    for (const ch of chars) {
      const { adv, px } = raw[ch];
      let w = adv; for (const p of px) w = Math.max(w, p[0] + 1);
      const h = bot - top + 1;
      const rows = [];
      for (let y = 0; y < h; y++) {
        let bits = 0n;
        for (const p of px) if (p[1] - top === y && p[0] >= 0) bits |= 1n << BigInt(p[0]);
        rows.push(bits.toString(36));
      }
      res[ch] = [adv, rows.join('.')];
    }
    return { top, h: bot - top + 1, g: res };
  }, { b64, size, chars: [...new Set(SETS[size])] });
}
await b.close();

let js = '/* LATENT CLASH — STAGE: baked pixel glyphs (generated by tools/stages-glyphs.mjs; do not edit).\n' +
  ' * Source: Fusion Pixel Font (OFL 1.1). Per size: h = rows, g[ch] = [advance, rows] where rows\n' +
  ' * are base-36 bit masks (bit x = column x), joined by ".". */\n' +
  '(function () { \'use strict\'; var LC = window.LC = window.LC || {}; (LC.stages = LC.stages || {})._glyphs = ' +
  JSON.stringify(out) + '; })();\n';
fs.writeFileSync(path.join(ROOT, 'src', 'stages', 'glyphs.js'), js);
console.log('wrote src/stages/glyphs.js', js.length, 'bytes', Object.keys(out).map((s) => s + ':h' + out[s].h).join(' '));
